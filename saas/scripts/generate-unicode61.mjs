// Reproduce the search boundary table from SQLite's public-domain source.
// Download the pinned URL below to a local file, then run:
// node scripts/generate-unicode61.mjs path/to/fts5_unicode2.c [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

const url = 'https://raw.githubusercontent.com/sqlite/sqlite/version-3.50.4/ext/fts5/fts5_unicode2.c';
const sha256 = 'b2defbe5df532c8fa646f8e4d3044f00cd59c1d3ffe715e6ca49ae7657a72308';
if (!process.argv[2]) throw Error('Pass the downloaded, pinned fts5_unicode2.c source path');
const source = readFileSync(process.argv[2]);
assert.equal(createHash('sha256').update(source).digest('hex'), sha256, 'SQLite source bytes differ from the pinned version');
const array = name => {
  const body = source.toString('utf8').match(new RegExp('static u16 ' + name + '\\[\\] = \\{([^}]+)\\}'))?.[1];
  assert.ok(body, 'Missing SQLite category array ' + name);
  return body.match(/\d+/g).map(Number);
};
const blocks = array('aFts5UnicodeBlock'), starts = array('aFts5UnicodeMap'), data = array('aFts5UnicodeData');
assert.equal(starts.length, data.length);
// Same lookup as sqlite3Fts5UnicodeCategory, including its category0 fallback.
function category(code) {
  if (code >= 1 << 20) return 0;
  let low = blocks[code >> 16], high = blocks[1 + (code >> 16)], result = -1;
  const key = code & 0xffff;
  while (high > low) {
    const middle = (high + low) >> 1;
    if (key >= starts[middle]) { result = middle; low = middle + 1; }
    else high = middle;
  }
  if (result < 0 || key >= starts[result] + (data[result] >> 5)) return 0;
  const value = data[result] & 0x1f;
  return value === 30 ? ((key - starts[result]) & 1 ? 5 : 9) : value;
}
// unicodeSetCategories("L* N* Co") also enables category0 (unassigned).
const tokens = new Set([0, 5, 6, 7, 8, 9, 13, 14, 15, 30, 31]), ranges = [];
for (let code = 0; code <= 0x10ffff; code++) {
  // READ_UTF8 in the matching fts5_tokenize.c maps surrogate scalars and
  // U+FFFE/U+FFFF to U+FFFD before the category lookup.
  const decoded = (code >= 0xd800 && code <= 0xdfff) || code === 0xfffe || code === 0xffff ? 0xfffd : code;
  if (tokens.has(category(decoded))) continue;
  if (ranges.length && ranges.at(-1) === code) ranges[ranges.length - 1] = code + 1;
  else ranges.push(code, code + 1);
}
const lines = [];
for (let index = 0; index < ranges.length; index += 12) lines.push('    ' + ranges.slice(index, index + 12).map(value => '0x' + value.toString(16)).join(', ') + ',');
const output = `// Generated by scripts/generate-unicode61.mjs; do not edit the range table.
// SQLite public-domain Unicode61 category source: ${url}
// Source SHA256: ${sha256}
// UTF-8 scalar decoding: https://raw.githubusercontent.com/sqlite/sqlite/version-3.50.4/ext/fts5/fts5_tokenize.c (READ_UTF8).
// Half-open separator ranges for default L* N* Co, including SQLite's
// category0 token fallback and decoded replacement characters.
// Marks/underscore grouping is handled by the caller.
const separators = [
${lines.join('\n')}
];

/** True for a decoded default Unicode61 token character (before folding). */
export function unicode61Token(code: number): boolean {
    let low = 0, high = separators.length / 2;
    while (low < high) {
        const middle = (low + high) >>> 1;
        if (code < separators[middle * 2]!) high = middle;
        else if (code >= separators[middle * 2 + 1]!) low = middle + 1;
        else return false;
    }
    return true;
}
`;
const destination = new URL('../src/release/unicode61.ts', import.meta.url);
if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), output);
else writeFileSync(destination, output);
console.log(`${ranges.length / 2} Unicode61 separator ranges, ${Buffer.byteLength(output)} bytes; ${process.argv.includes('--check') ? 'unchanged' : 'generated'}`);
